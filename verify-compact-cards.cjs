const { chromium } = require('C:/Users/root/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:5173/');
    await page.waitForFunction(() => window.workflow);
    const ids = await page.evaluate(() => {
      workflow.state.settings.mode = 'demo';
      const task = workflow.state.products[0].tasks[0];
      return { task: task.id, prompt: task.prompt, primary: task.primaryId, second: task.versions[1].id, count: task.versions.length };
    });
    assert.equal(await page.locator('.task-card textarea').count(), 0);
    assert.equal(await page.locator('.task-card').count(), 10);
    const card = page.locator(`.task-card[data-task="${ids.task}"]`);
    const bounds = await card.boundingBox();
    assert.ok(bounds.height < 470, `Card height: ${bounds.height}`);
    assert.equal((await card.locator('.reference').boundingBox()).width, 56);
    assert.ok((await card.locator('.result-area').boundingBox()).height > 240);
    assert.equal((await page.locator('.task-grid').evaluate(e => getComputedStyle(e).gridTemplateColumns)).split(' ').length, 3);
    await card.locator(`[data-action=select-version][data-version="${ids.primary}"]`).check();
    await card.locator(`[data-action=choose-version][data-version="${ids.second}"]`).click();
    assert.equal(await page.locator('#modal').evaluate(e => e.open), false);
    assert.equal(await card.locator('input:checked').count(), 1);
    assert.equal(await card.locator(`[data-action=select-version][data-version="${ids.primary}"]`).isChecked(), false);
    assert.equal(await page.evaluate(() => {
      const task = workflow.state.products[0].tasks[0];
      const source = workflow.bridge.snapshot().sheets.preview.cellData[3][4].p.drawings;
      return Object.values(source)[0].source === task.versions[1].source;
    }), true);
    await card.locator('[data-action=edit-prompt]').click();
    const editor = page.locator('#prompt-form textarea');
    assert.equal(await editor.inputValue(), ids.prompt);
    await editor.fill('未保存的草稿');
    await page.locator('#prompt-form [data-action=close-modal]').click();
    assert.equal(await page.evaluate(() => workflow.state.products[0].tasks[0].prompt), ids.prompt);
    await card.locator('[data-action=edit-prompt]').click();
    const revised = '编辑后的尺寸图提示词，保留实拍产品比例和实际尺寸。';
    await editor.fill(revised);
    await page.evaluate(() => workflow.queue.pause(true));
    assert.equal(await editor.inputValue(), revised, 'Background renders preserve the unsaved draft');
    await page.locator('#prompt-form button[type=submit]').click();
    await page.waitForFunction(() => !document.querySelector('#modal').open);
    let task = await page.evaluate(() => workflow.state.products[0].tasks[0]);
    assert.equal(task.prompt, revised);
    assert.equal(task.promptHistory.at(-1).prompt, ids.prompt);
    assert.equal(task.primaryId, ids.second);
    assert.deepEqual(task.selectedIds, [ids.second]);
    assert.equal(await page.evaluate(() => workflow.bridge.snapshot().sheets.preview.cellData[2][4].v), revised);
    await card.locator('[data-action=edit-prompt]').click();
    await page.locator('.prompt-editor-history summary').click();
    await page.screenshot({ path: 'compact-prompt-preview.png' });
    await page.locator('.prompt-editor-history [data-action=restore-prompt]').first().click();
    await page.waitForFunction(() => !document.querySelector('#modal').open);
    assert.equal(await page.evaluate(() => workflow.state.products[0].tasks[0].prompt), ids.prompt);
    await card.locator('[data-action=generate-image]').click();
    await page.evaluate(() => workflow.queue.pause(false));
    await page.waitForFunction(count => workflow.state.products[0].tasks[0].versions.length === count + 1, ids.count);
    task = await page.evaluate(() => workflow.state.products[0].tasks[0]);
    assert.equal(task.versions.at(-1).prompt, ids.prompt);
    assert.equal(task.primaryId, ids.second);
    assert.deepEqual(task.selectedIds, [ids.second]);
    await card.locator('.result-image').click();
    assert.equal(await page.locator('#modal .large-preview').count(), 1);
    await page.locator('#modal [data-action=close-modal]').click();
    for (const [width, columns] of [[1920, 4], [1100, 2], [780, 1]]) {
      await page.setViewportSize({ width, height: 1000 });
      assert.equal((await page.locator('.task-grid').evaluate(e => getComputedStyle(e).gridTemplateColumns)).split(' ').length, columns);
      assert.ok(await card.evaluate(e => e.scrollWidth <= e.clientWidth), `Card overflow at ${width}`);
    }
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.screenshot({ path: 'compact-cards-preview.png' });
    await page.click('#save');
    await page.waitForFunction(() => document.querySelector('#save-status').textContent === '已保存到本机');
    await page.reload();
    await page.waitForFunction(() => window.workflow);
    task = await page.evaluate(() => workflow.state.products[0].tasks[0]);
    assert.equal(task.primaryId, ids.second);
    assert.equal(task.versions.length, ids.count + 1);
    assert.equal(task.prompt, ids.prompt);
    assert.deepEqual(task.selectedIds, [ids.second]);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ compactCards: true, responsiveColumns: true, promptCancelSaveRestore: true, draftSurvivesRender: true, tableBackfill: true, retryPreservesChoices: true, reload: true }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
